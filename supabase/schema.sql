-- Drop legacy table if present
DROP TABLE IF EXISTS public.admin_users CASCADE;

-- 1. STOREFRONT PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id          BIGINT PRIMARY KEY,
    name        TEXT NOT NULL,
    brand       TEXT,
    capacity    TEXT,
    type        TEXT,
    price       NUMERIC DEFAULT 0,
    description TEXT,
    featured    BOOLEAN DEFAULT FALSE,
    image       TEXT,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 2. SERVICE BOOKINGS TABLE
CREATE TABLE IF NOT EXISTS public.bookings (
    id             TEXT PRIMARY KEY DEFAULT ('BK-' || floor(random()*9000+1000)::TEXT),
    name           TEXT NOT NULL,
    phone          TEXT NOT NULL,
    email          TEXT,
    service_type   TEXT,
    ac_type        TEXT,
    preferred_date TEXT,
    address        TEXT,
    status         TEXT DEFAULT 'Pending',
    notes          TEXT,
    created_at     TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CONTACT MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.messages (
    id         TEXT PRIMARY KEY DEFAULT ('MSG-' || floor(random()*90000+10000)::TEXT),
    name       TEXT NOT NULL,
    phone      TEXT NOT NULL,
    email      TEXT,
    message    TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ADMIN USERS TABLE
CREATE TABLE IF NOT EXISTS public.admin (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL DEFAULT 'Administrator',
    email         TEXT UNIQUE NOT NULL,
    username      TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role          TEXT DEFAULT 'superadmin',
    created_at    TIMESTAMPTZ DEFAULT NOW()
);

-- 5. SETTINGS / CONFIG TABLE (AMC Pricing, etc.)
CREATE TABLE IF NOT EXISTS public.settings (
    key        TEXT PRIMARY KEY,
    value      JSONB NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. INVOICE GENERATOR CUSTOMERS TABLE
CREATE TABLE IF NOT EXISTS public.customers (
    id              TEXT PRIMARY KEY,
    name            TEXT NOT NULL,
    address         TEXT,
    mobile          TEXT,
    gstin           TEXT,
    ship_name       TEXT,
    ship_address    TEXT,
    ship_mobile     TEXT,
    ship_ref        TEXT,
    place_of_supply TEXT,
    notes           TEXT,
    created         TIMESTAMPTZ DEFAULT NOW(),
    updated         TIMESTAMPTZ DEFAULT NOW()
);

-- 7. INVOICE GENERATOR DOCUMENTS / BILLS TABLE
CREATE TABLE IF NOT EXISTS public.documents (
    id            TEXT PRIMARY KEY,
    doc_type      TEXT NOT NULL,
    doc_no        TEXT NOT NULL,
    doc_date      TEXT,
    customer_id   TEXT,
    customer_name TEXT,
    taxable       NUMERIC DEFAULT 0,
    tax           NUMERIC DEFAULT 0,
    other_charges NUMERIC DEFAULT 0,
    total         NUMERIC DEFAULT 0,
    advance       NUMERIC DEFAULT 0,
    balance       NUMERIC DEFAULT 0,
    json_data     JSONB NOT NULL,
    created       TIMESTAMPTZ DEFAULT NOW()
);

-- 8. INVENTORY STOCK CATALOG TABLE
CREATE TABLE IF NOT EXISTS public.stock (
    id       TEXT PRIMARY KEY,
    model    TEXT NOT NULL,
    hsn      TEXT,
    ton      TEXT,
    type     TEXT,
    mrp      NUMERIC DEFAULT 0,
    rate     NUMERIC DEFAULT 0,
    cost     NUMERIC DEFAULT 0,
    gst      NUMERIC DEFAULT 0,
    qty      NUMERIC DEFAULT 0,
    reorder  NUMERIC DEFAULT 0,
    location TEXT,
    updated  TIMESTAMPTZ DEFAULT NOW()
);

-- 9. INVENTORY STOCK MOVEMENTS TABLE
CREATE TABLE IF NOT EXISTS public.stock_moves (
    id        TEXT PRIMARY KEY,
    date      TEXT,
    stock_id  TEXT,
    model     TEXT,
    direction TEXT,
    qty       NUMERIC DEFAULT 0,
    balance   NUMERIC DEFAULT 0,
    doc_type  TEXT,
    doc_no    TEXT,
    party     TEXT,
    note      TEXT,
    created   TIMESTAMPTZ DEFAULT NOW()
);

