-- Indexes for high performance
CREATE INDEX IF NOT EXISTS idx_bookings_status     ON public.bookings(status);
CREATE INDEX IF NOT EXISTS idx_bookings_created_at ON public.bookings(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_messages_created_at ON public.messages(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_brand      ON public.products(brand);
CREATE INDEX IF NOT EXISTS idx_products_featured   ON public.products(featured);
CREATE INDEX IF NOT EXISTS idx_admin_username      ON public.admin(username);
CREATE INDEX IF NOT EXISTS idx_docs_type_no        ON public.documents(doc_type, doc_no);
CREATE INDEX IF NOT EXISTS idx_stock_model         ON public.stock(model);

